    /**
     * Returns the SHA-256 checksum (lowercase hex) of the given data.
     * Empty input returns an empty string.
     */
    public static String compute(byte[] data) {
        if (data == null || data.length == 0) {
            return "";
        }

        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest(data);

            StringBuilder sb = new StringBuilder(hash.length * 2);
            for (byte b : hash) {
                sb.append(String.format("%02x", b & 0xff));
            }
            return sb.toString();
        } catch (NoSuchAlgorithmException ex) {
            // SHA-256 is mandatory for every JVM - should never happen
            throw new IllegalStateException("SHA-256 not available", ex);
        }
    }

    /** Returns the SHA-256 checksum (lowercase hex) of the given file. */
    public static String compute(File file) throws IOException {
        if (file == null || !file.isFile()) {
            return "";
        }
        return compute(Files.readAllBytes(file.toPath()));
    }

    /** Returns the document blob of a bill (pdf_data, else odt_data). */
    public static byte[] getBillData(DBBill bill) {
        if (bill == null) {
            return null;
        }
        if (bill.pdf_data.value != null && bill.pdf_data.value.length > 0) {
            return bill.pdf_data.value;
        }
        return bill.odt_data.value;
    }

    /** Returns the stored checksum of a bill, or an empty string. */
