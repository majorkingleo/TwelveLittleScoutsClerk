    private boolean check() {
        if (selectedFile == null || !selectedFile.isFile()) {
            JOptionPane.showMessageDialog(this, MESSAGE_NO_FILE_SELECTED);
            return false;
        }
        try {
            parseAmount();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, MESSAGE_INVALID_AMOUNT);
            jTAmount.requestFocus();
            return false;
        }
        return true;
    }

    /**
     * Parses the amount text field. Empty input returns 0.0.
     */
    private double parseAmount() throws NumberFormatException {
        String text = jTAmount.getText().trim();
        if (text.isEmpty()) {
            return 0.0;
        }
        return Double.parseDouble(text.replace(",", "."));
    }

    public boolean pressedSave() {
        return saved;
    }

    /**
     * Validates and remembers the file to upload. Returns false and shows a
     * message when the file type is not supported.
     */
    private boolean setFile(File file) {
        if (file == null || !file.isFile()) {
            return false;
        }

        String lowerName = file.getName().toLowerCase();
        if (!lowerName.endsWith(".pdf") && !lowerName.endsWith(".odt")
                && !lowerName.endsWith(".jpg") && !lowerName.endsWith(".jpeg")) {
            JOptionPane.showMessageDialog(this, MESSAGE_UNSUPPORTED_TYPE);
            return false;
        }

        selectedFile = file;
        jLFileName.setText(file.getName());
        jBSave.setEnabled(true);
        return true;
    }

    private void initDropSupport() {
        TransferHandler th = new TransferHandler() {
            @Override
            public boolean canImport(TransferSupport support) {
                return support.isDrop()
                        && support.isDataFlavorSupported(DataFlavor.javaFileListFlavor);
            }

            @Override
            public boolean importData(TransferSupport support) {
                if (!canImport(support)) {
                    return false;
                }
                try {
                    Transferable transferable = support.getTransferable();
                    @SuppressWarnings("unchecked")
                    List<File> files = (List<File>) transferable.getTransferData(
                            DataFlavor.javaFileListFlavor);
                    for (File file : files) {
                        setFile(file);
                    }
                    return true;
                } catch (UnsupportedFlavorException | IOException ex) {
                    return false;
                }
            }
        };

        setTransferHandlerRecursive(getContentPane(), th);
    }

    private void setTransferHandlerRecursive(Container container, TransferHandler th) {
        for (java.awt.Component comp : container.getComponents()) {
            if (comp instanceof JComponent) {
                ((JComponent) comp).setTransferHandler(th);
            }
            if (comp instanceof Container) {
                setTransferHandlerRecursive((Container) comp, th);
            }
        }
    }
