    private void jBChooseFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBChooseFileActionPerformed

        JFileChooser chooser = new JFileChooser(mainwin.getLastOpenPath());
        chooser.setDialogTitle(MESSAGE_TITLE);
        chooser.setFileFilter(new FileNameExtensionFilter("PDF, ODT, JPEG", "pdf", "odt", "jpg", "jpeg"));
        int result = chooser.showOpenDialog(this);
        if (result != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File selected = chooser.getSelectedFile();
        mainwin.setLastOpenPath(selected.getParent());
        setFile(selected);
    }//GEN-LAST:event_jBChooseFileActionPerformed

    private void jBSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBSaveActionPerformed

        if (!check()) {
            return;
        }

        final File file = selectedFile;
        final double amountVal = parseAmount();

        new AutoMBox(UploadExternalBill.class.getName()) {
            @Override
            public void do_stuff() throws Exception {
                byte[] data = Files.readAllBytes(file.toPath());
                String lowerName = file.getName().toLowerCase();

                Transaction trans = getTransaction();
                int newIdx = mainwin.getNewSequenceValue(DBBill.BILL_IDX_SEQUENCE);

                DBBill bill = new DBBill();
                bill.idx.loadFromCopy(newIdx);
                bill.bp_idx.loadFromCopy(mainwin.getBPIdx());
                bill.billingnr.loadFromString(String.valueOf(newIdx));
                bill.file_name.loadFromString(file.getName());
                bill.state.handler.setValue(DBBill.State.NORMAL.ordinal());
                bill.direction.handler.setValue(DBBill.Direction.INCOMING.ordinal());
                bill.amount.loadFromCopy(amountVal);
                if (lowerName.endsWith(".odt")) {
                    bill.odt_data.value = data;
                } else {
                    // pdf and jpeg are stored in the pdf_data blob
                    bill.pdf_data.value = data;
                }
                DefaultInsertOrUpdater.insertOrUpdateValuesWithPrimKey(
                        trans, bill, bill.hist, root.getUserName());
                trans.commit();

                saved = true;
                JOptionPane.showMessageDialog(UploadExternalBill.this, MESSAGE_UPLOAD_OK);
                close();
            }
        };
    }//GEN-LAST:event_jBSaveActionPerformed

