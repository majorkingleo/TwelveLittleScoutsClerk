    private void jBDownloadPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBDownloadPDFActionPerformed
        String name = entity.file_name.toString();
        if (name.isEmpty()) {
            name = "rechnung.pdf";
        } else {
            String lower = name.toLowerCase();
            // Keep original extension for generic files (e.g. uploaded JPEG),
            // otherwise treat the blob as a generated PDF.
            if (!lower.endsWith(".pdf") && !lower.endsWith(".jpg") && !lower.endsWith(".jpeg")) {
                name = name.replaceFirst("\\.[^.]+$", ".pdf");
                if (!name.endsWith(".pdf")) {
                    name = name + ".pdf";
                }
            }
        }

        downloadFile(entity.pdf_data.value, name);
    }//GEN-LAST:event_jBDownloadPDFActionPerformed

    private void jBViewPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBViewPDFActionPerformed
        if (entity.pdf_data.value == null || entity.pdf_data.value.length == 0) {
            return;
        }
        new AutoMBox(ViewBill.class.getName()) {
            @Override
            public void do_stuff() throws Exception {
                File tmpFile = File.createTempFile("bill_", ".pdf");
                tmpFile.deleteOnExit();
                try (FileOutputStream fos = new FileOutputStream(tmpFile)) {
                    fos.write(entity.pdf_data.value);
                }
                String openCmd = mainwin.getRoot().getSetup().getLocalConfig(FrameWorkConfigDefinitions.OpenCommand);
                Runtime.getRuntime().exec(new String[]{openCmd, tmpFile.getAbsolutePath()});
            }
        };
    }//GEN-LAST:event_jBViewPDFActionPerformed

    private void downloadFile(byte[] data, String suggestedName) {
        if (data == null || data.length == 0) {
            return;
        }

        JFileChooser chooser = new JFileChooser(mainwin.getLastOpenPath());
        chooser.setDialogTitle("Save File");
        chooser.setSelectedFile(new java.io.File(suggestedName));
        int result = chooser.showSaveDialog(this);
        if (result != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File target = chooser.getSelectedFile();
        mainwin.setLastOpenPath(target.getParent());

        new AutoMBox(ViewBill.class.getName()) {
            @Override
            public void do_stuff() throws Exception {
                try (FileOutputStream fos = new FileOutputStream(target)) {
                    fos.write(data);
                }
            }
        };
    }

